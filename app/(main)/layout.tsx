import { cookies } from "next/headers";
import type { Metadata } from "next";
import { Fraunces, Manrope } from "next/font/google";
import "@/app/globals.css";
import { cn } from "@/lib/utils";
import { Header } from "@/app/index";
import Footer from "@/components/Footer";
import CartHydrator from "@/components/CartHydrator";
import { CurrencyProvider } from "@/components/providers/currency-provider";
import { BASE_CURRENCY, isCurrencyCode } from "@/lib/currency/config";
import { getRates } from "@/lib/currency/rates";


const fraunces = Fraunces({
  subsets: ["latin"],
  variable: "--font-fraunces",
  display: "swap",
});

const manrope = Manrope({
  subsets: ["latin"],
  variable: "--font-manrope",
  display: "swap",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const [cookieStore, { rates }] = await Promise.all([cookies(), getRates()]);
  const savedCurrency = cookieStore.get("currency")?.value;
  const initialCurrency =
    savedCurrency && isCurrencyCode(savedCurrency) ? savedCurrency : BASE_CURRENCY;

  return (
    <html
      lang="en"
      className={cn("h-full", "antialiased", fraunces.variable, manrope.variable, "font-sans")}
    >
      <body className="min-h-full flex flex-col">
        <CurrencyProvider initialCurrency={initialCurrency} initialRates={rates}>
          <CartHydrator />
          <Header />
          <main className="flex-1">{children}</main>
          <Footer />
        </CurrencyProvider>
      </body>
    </html>
  );
}
